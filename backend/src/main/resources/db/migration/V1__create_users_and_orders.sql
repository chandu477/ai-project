CREATE TABLE app_user (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username            VARCHAR(50)    NOT NULL UNIQUE,
    monthly_salary      DECIMAL(12, 2) NOT NULL,
    years_of_experience INT            NOT NULL CHECK (years_of_experience >= 0)
);

CREATE TABLE customer_order (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT         NOT NULL REFERENCES app_user (id),
    amount  DECIMAL(12, 2) NOT NULL
);

CREATE INDEX idx_customer_order_user_id ON customer_order (user_id);
CREATE INDEX idx_app_user_monthly_salary ON app_user (monthly_salary);
CREATE INDEX idx_app_user_years_of_experience ON app_user (years_of_experience);
